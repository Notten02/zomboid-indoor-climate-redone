-- The player's side: the server sending each player their sample, a client receiving it and serving it through the
-- public API, joining and reconnecting, and the bridge heat source in multiplayer and single player.
local House = require("support/house")
local Sync = require("IndoorClimateRedone/Sync")

local function sentTo(game, player, command)
    local found = {}
    for _, message in ipairs(game.sent) do
        if message.player == player and message.module == Sync.MODULE
            and (not command or message.command == command) then
            found[#found + 1] = message
        end
    end
    return found
end

local function receive(game, command, args)
    game.events.OnServerCommand.trigger(Sync.MODULE, command, args)
end

local function sampleArgs(player, fields)
    local args = { airC = 20, baseRoomC = 20, targetC = 22, outdoorC = 10, vanillaAirC = 10, indoors = true,
        powered = true, roomKey = "vanilla:1", buildingKey = House.KEY, roomKind = "vanilla", leakScore = 0,
        openDoors = 0, openWindows = 0, hour = 100, playerId = player:getOnlineID() }
    for name, value in pairs(fields or {}) do
        args[name] = value
    end
    return args
end

insulate("server sync", function()
    it("sends a player their sample once they are in a room", function()
        local game, world, _, Climate = House.setup()
        local player = world:player(11, 11, 0)
        local other = world:player(5, 5, 0)
        game.advance(1)
        local messages = sentTo(game, player, Sync.SAMPLE)
        assert.are.equal(1, #messages)
        local args = messages[1].args
        assert.are.equal(player:getOnlineID(), args.playerId)
        assert.are.equal(assert(Climate).sample(player).airC, args.airC)
        assert.are.equal("vanilla:1", args.roomKey)
        assert.are.equal(0, #sentTo(game, other))
    end)

    it("sends again only on a 0.2 C change or after the heartbeat", function()
        local game, world = House.setup()
        local player = world:player(11, 11, 0)
        game.advance(1)
        -- An unpowered house at 12 C with 10 C outside hardly moves: nothing for ten game minutes (25 real s).
        game.advance(10)
        assert.are.equal(1, #sentTo(game, player))
        game.advance(3)
        assert.are.equal(2, #sentTo(game, player))
        -- A powered house warms fast and is sent as it goes.
        game.power = true
        game.advance(30)
        assert.is_true(#sentTo(game, player) > 5)
    end)

    it("sends another room at once, and CLEAR once when the player walks out", function()
        local game, world = House.setup()
        local player = world:player(11, 11, 0)
        game.advance(1)
        player:moveTo(14, 12, 0)
        game.advance(0.1)
        local messages = sentTo(game, player, Sync.SAMPLE)
        assert.are.equal("vanilla:2", messages[#messages].args.roomKey)
        player:moveTo(5, 5, 0)
        game.advance(30)
        assert.are.equal(1, #sentTo(game, player, Sync.CLEAR))
        assert.are.equal(player:getOnlineID(), sentTo(game, player, Sync.CLEAR)[1].args.playerId)
    end)

    it("answers a client's HELLO at once with the sample, or CLEAR outdoors", function()
        local game, world = House.setup()
        local player = world:player(11, 11, 0)
        game.advance(1)
        local before = #sentTo(game, player, Sync.SAMPLE)
        game.events.OnClientCommand.trigger(Sync.MODULE, Sync.HELLO, player, {})
        assert.are.equal(before + 1, #sentTo(game, player, Sync.SAMPLE))
        local outside = world:player(5, 5, 0)
        game.advance(1)
        game.events.OnClientCommand.trigger(Sync.MODULE, Sync.HELLO, outside, {})
        assert.are.equal(1, #sentTo(game, outside, Sync.CLEAR))
        game.events.OnClientCommand.trigger("SomeOtherMod", Sync.HELLO, outside, {})
        assert.are.equal(1, #sentTo(game, outside))
    end)

    it("sends a player who reconnects their sample again", function()
        local game, world = House.setup()
        local player = world:player(11, 11, 0)
        game.advance(1)
        table.remove(world.players, 1)
        game.advance(1)
        local again = world:player(11, 11, 0)
        game.advance(1)
        assert.are.equal(1, #sentTo(game, again, Sync.SAMPLE))
        assert.are.equal(1, #sentTo(game, player, Sync.SAMPLE))
    end)

    it("clears every player when the simulation is switched off", function()
        local game, world = House.setup()
        local a = world:player(11, 11, 0)
        local b = world:player(14, 12, 0)
        game.advance(1)
        game.sandbox.Enabled = false
        game.advance(1)
        assert.are.equal(1, #sentTo(game, a, Sync.CLEAR))
        assert.are.equal(1, #sentTo(game, b, Sync.CLEAR))
    end)

    it("sends nothing in single player", function()
        local game, world = House.setup({ side = "sp" })
        world:player(11, 11, 0)
        game.advance(30)
        assert.are.equal(0, #game.sent)
    end)
end)

insulate("client", function()
    it("serves the sample the server sent through the API", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        local other = world:player(14, 12, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player, { airC = 19.5, baseRoomC = 19.5 }))
        local s = IndoorClimateLite.getTemperatureSample(player)
        assert.are.equal("IndoorClimateLite", s.source)
        assert.is_true(s.active)
        assert.is_true(s.indoors)
        assert.are.equal(19.5, s.airC)
        assert.are.equal("vanilla:1", s.roomKey)
        assert.is_nil(s.playerId)
        assert.are.equal(19.5, IndoorClimateLite.getTemperatureForPlayer(player))
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(other))
        assert.is_nil(IndoorClimateLite.getTemperatureSample(other).roomKey)
    end)

    it("drops the sample on CLEAR, and hides it outdoors and in a vehicle before the CLEAR comes", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player))
        player:moveTo(5, 5, 0)
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(player))
        player:moveTo(11, 11, 0)
        assert.is_not_nil(IndoorClimateLite.getLiveTemperatureSample(player))
        player.vehicle = {}
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(player))
        player.vehicle = nil
        receive(game, Sync.CLEAR, { playerId = player:getOnlineID() })
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(player))
        assert.is_true(IndoorClimateLite.getTemperatureSample(player).indoors)
        assert.is_nil(IndoorClimateLite.getTemperatureSample(player).roomKey)
    end)

    it("ignores other mods' commands and malformed ones", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        game.events.OnServerCommand.trigger("SomeOtherMod", Sync.SAMPLE, sampleArgs(player))
        receive(game, Sync.SAMPLE, { playerId = player:getOnlineID() })
        receive(game, Sync.SAMPLE, nil)
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(player))
    end)

    it("asks the server for its sample when a player joins", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        game.events.OnCreatePlayer.trigger(0, player)
        assert.are.equal(1, #game.clientSent)
        assert.are.same({ player = player, module = Sync.MODULE, command = Sync.HELLO, args = {} }, game.clientSent[1])
    end)

    it("knows the temperature of the player's own room only", function()
        local game, world = House.setup({ side = "client" })
        game.climate.vanillaC = 9
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player, { airC = 21, baseRoomC = 20.5 }))
        assert.are.equal(20.5, IndoorClimateLite.getTemperatureForSquare(world:square(12, 13, 0), player))
        assert.are.equal(9, IndoorClimateLite.getTemperatureForSquare(world:square(14, 12, 0), player))
        assert.are.equal(9, IndoorClimateLite.getTemperatureForSquare(world:square(8, 8, 0), player))
    end)

    it("forgets everything on disconnect", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player))
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        game.events.OnDisconnect.trigger()
        assert.is_nil(IndoorClimateLite.getLiveTemperatureSample(player))
        assert.are.equal(0, #game.heatSources)
    end)

    it("shows on the client what the server simulated", function()
        local game, world, _, Climate = House.setup({ power = true })
        local player = world:player(11, 11, 0)
        game.advance(45)
        local serverSample = assert(Climate).sample(player)
        local messages = sentTo(game, player, Sync.SAMPLE)
        local last = messages[#messages]

        local clientGame, clientWorld = House.setup({ side = "client", power = true })
        local here = clientWorld:player(11, 11, 0)
        here.onlineId = player:getOnlineID()
        receive(clientGame, last.command, last.args)
        local s = IndoorClimateLite.getTemperatureSample(here)
        assert.near(serverSample.airC, s.airC, Sync.CHANGE_C)
        assert.are.equal(serverSample.roomKey, s.roomKey)
        assert.are.equal(serverSample.buildingKey, s.buildingKey)
        assert.are.equal(serverSample.powered, s.powered)
    end)
end)

insulate("bridge", function()
    it("makes the game's air at the player match a warmer room, and follows the player", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player, { baseRoomC = 20, vanillaAirC = 10 }))
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        local source = game.heatSources[1]
        assert.are.equal(1, source:getRadius())
        assert.are.equal(27, source:getTemperature())
        assert.are.equal(20, getClimateManager():getAirTemperatureForSquare(player:getCurrentSquare()))
        player:moveTo(12, 12, 0)
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        assert.are.equal(12, game.heatSources[1]:getX())
        assert.are.equal(20, getClimateManager():getAirTemperatureForSquare(player:getCurrentSquare()))
    end)

    it("uses the game's indoor correction for hot air", function()
        local Bridge = require("IndoorClimateRedone/Game/Bridge")
        assert.are.equal(27, Bridge.sourceTemperature(20, 10))
        assert.are.equal(31, Bridge.sourceTemperature(33, 32))
        assert.are.equal(33, Bridge.sourceTemperature(40, 38))
        assert.are.equal(19, Bridge.sourceTemperature(20.6, 31.4))
    end)

    it("leaves a room no warmer than the game's air, a vehicle, the outdoors and NativeBridge off alone", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player, { baseRoomC = 10.25, vanillaAirC = 10 }))
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
        receive(game, Sync.SAMPLE, sampleArgs(player, { baseRoomC = 18, vanillaAirC = 10 }))
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        player.vehicle = {}
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
        player.vehicle = nil
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        player:moveTo(5, 5, 0)
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
        player:moveTo(11, 11, 0)
        game.sandbox.NativeBridge = false
        IndoorClimateLite.refreshConfig()
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
    end)

    it("is removed when the server clears the sample", function()
        local game, world = House.setup({ side = "client" })
        local player = world:player(11, 11, 0)
        receive(game, Sync.SAMPLE, sampleArgs(player))
        game.advance(0.1)
        assert.are.equal(1, #game.heatSources)
        receive(game, Sync.CLEAR, { playerId = player:getOnlineID() })
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
    end)

    it("is placed on a dedicated server too, which works out body warmth from its own air", function()
        local game, world, _, Climate = House.setup({ power = true })
        local player = world:player(11, 11, 0)
        game.advance(240)
        local sample = assert(Climate).sample(player)
        assert.is_true(sample.airC > 20)
        assert.are.equal(1, #game.heatSources)
        assert.are.equal(1, game.heatSources[1]:getRadius())
        assert.near(sample.airC, getClimateManager():getAirTemperatureForSquare(player:getCurrentSquare()), 0.5)
        assert.are.equal(10, sample.vanillaAirC)
        player:moveTo(12, 12, 0)
        game.advance(0.1)
        assert.are.equal(12, game.heatSources[1]:getX())
        -- Gone when the player leaves the room, and when they leave the server.
        player:moveTo(5, 5, 0)
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
        player:moveTo(11, 11, 0)
        game.advance(1)
        assert.are.equal(1, #game.heatSources)
        table.remove(world.players, 1)
        game.advance(0.1)
        assert.are.equal(0, #game.heatSources)
    end)

    it("runs in single player, and the simulation reads the game's air without it", function()
        local game, world, _, Climate = House.setup({ side = "sp", power = true })
        local player = world:player(11, 11, 0)
        game.advance(240)
        local sample = assert(Climate).sample(player)
        assert.is_true(sample.airC > 20)
        assert.are.equal(1, #game.heatSources)
        assert.near(sample.airC, getClimateManager():getAirTemperatureForSquare(player:getCurrentSquare()), 0.5)
        assert.are.equal(10, sample.vanillaAirC)
        assert.are.equal(1, #game.heatSources)
    end)
end)
